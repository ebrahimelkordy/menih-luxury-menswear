export function translate(key: string, lang: Language, params?: Record<string, string>): string {
  const entry = translations[key];
  if (!entry) return key;
  let text = entry[lang] || entry.en;
  if (params) {
    Object.entries(params).forEach(([k, val]) => {
      text = text.replace(`{${k}}`, val);
    });
  }
  return text;
}

